"""Audit existing R5B evidence without changing registered fits or predictors."""
import hashlib
import json
import sys
from pathlib import Path
import numpy as np
import pandas as pd
HERE=Path(__file__).resolve().parent
STUDY=HERE.parent
sys.path.insert(0,str(STUDY/'src'))
from audit5b import dump,clean_json,bilingual,physical_charge
from emodel import OCP,sim_cccv,bounds_violation

if __name__=='__main__':
    result={}
    synthetic=pd.read_csv(STUDY/'stage_1/outputs/S1_synthetic.csv')
    result['synthetic']={'rows':len(synthetic),'valid_states':int(synthetic.valid.sum()),
        'finite_counts':{c:int(np.isfinite(synthetic[c]).sum()) for c in ['Q_C20_true','Q_C20_fit','Q_fc_true','Q_fc_fit','beta_true','beta_fit']},
        'median_abs_LAM_NE_error_pct':float((synthetic.LAMNE_fit-synthetic.LAM_NE).abs().median()*100),
        'median_abs_LAM_PE_error_pct':float((synthetic.LAMPE_fit-synthetic.LAM_PE).abs().median()*100),
        'current_profile_deviation':'Synthetic current is model-generated CCCV, not the measured anchor1 profile specified in the prompt and protocol; documented D1.2.'}
    ocp=OCP('main')
    qn,qp,tn,tp=143.,106.,1.2,.93
    invalid=(qn,qp,tn*qn+tp*qp,tn)
    simulated=sim_cccv([invalid]*4,[.002]*4,[.01]*4,ocp=ocp)
    result['invalid_theta_test']={'theta_n_at_start':tn,'bounds_violation':bounds_violation(np.array([0.]),invalid,ocp),
        'Q_fc_returned':simulated,'invalid_state_rejected':not np.isfinite(simulated),
        'interpretation':'Any finite charge result from this invalid state contradicts the required hard stoichiometry rejection.'}
    calibration=json.loads((STUDY/'stage_2/outputs/S2_ck0_check.json').read_text())
    checks={}
    for name,obj in calibration.items():
        xs=np.asarray(obj['ref_fit'],float)
        q=obj['chain']['Q_fc_obs']
        checks[name]={'reference_fit_charge_valid':all(physical_charge(x,q,ocp) for x in xs),
            'sum_R_Ohm':float(xs[:,4].sum()),'CCCV_resistance_floor_used':bool(xs[:,4].sum()<=0),
            'registered_CK0_credible':obj['credible'],'root_error_Ah':obj['Q_C20_err_vs_10041'],
            'CCCV_chain_error_Ah':obj['chain']['Q_C20_from_anchor']-100.41,
            'model_uses_tail_in_discharge_fit':False,
            'source_window_evidence':'stage_2/run_2.py uses d in [5,85.412] then [::10]; last15Ah only used for prediction diagnostics.'}
    result['CK0']=checks
    result['protocol_hashes']={}
    for sha in sorted(STUDY.rglob('protocol.sha256')):
        if 'cache' in sha.parts:continue
        path=sha.with_suffix('.json')
        result['protocol_hashes'][str(path.relative_to(STUDY))]=hashlib.sha256(path.read_bytes()).hexdigest()==sha.read_text().split()[0]
    dump(HERE/'outputs/audit.json',clean_json(result))
    bilingual(HERE/'REPORT.md','Independent R5B evidence audit',
      f'''Exposed-exploratory; proxies are not hidden truth. Existing main configurations and fits are preserved.

All 30 synthetic cases have finite reported capacity/beta values. Missing recovery summaries for LAM_NE/LAM_PE are supplied in audit.json. The synthetic current was generated by the model, contrary to the specified replay; its numerical pass therefore supports only that model-generated experiment.

CK0 main passes its registered root/step gate, but the separately fitted CK0 start state differs from the simulated CCCV end state. Its chain predicts about 102.399 Ah. The main anchor0 fitted sum R is negative, while the CCCV simulator replaces that denominator by 1e-6; this is an unregistered numerical convention, not the exact V=U+RI CV formula.

An invalid theta_n=1.2 start returned Q_fc={simulated}. A finite return means the charge simulator silently interpolates/clips invalid states. Future profile/simulation outputs must explicitly reject invalid states; no passing model may rely on this behavior. The existing modules are not rewritten because of the concurrency guard. Stage3 independently filters validity and treats undefined roots as unavailable.

This audit does not change CK0's registered scalar credibility label or select a predictor. It distinguishes that gate from a fully validated anchor-to-discharge chain.''',
      f'''已曝光探索性研究；代理不是隐藏真值。保留现有主配置和拟合。

三十个合成情景的容量/β 数值均有限；缺少的 LAM_NE/LAM_PE 恢复汇总补在 audit.json。合成电流由模型生成，未按要求回放实测电流，因此通过数值只能支持该模型生成实验。

CK0 主配置通过登记的容量/台阶门，但独立拟合的 CK0 起点与模拟 CCCV 末端不同；后者的链条预测约 102.399 Ah。锚点0的拟合总 R 为负，CCCV 模拟器却把分母替换成 1e-6，这是未登记数值约定，不是精确的 V=U+RI 恒压公式。

theta_n=1.2 的无效起点返回 Q_fc={simulated}。有限返回说明充电模拟对越界状态默默插值/截平；后续剖面及模拟必须明确拒绝无效状态，合格模型不能依赖此行为。按并发防护不改写原模块；阶段3独立过滤有效性，不可求根如实标记。

本审计不改变 CK0 登记的标量可信度标签，也不选择预测器，而是区分该门与完整锚点到放电链条的验证。''')
    print(json.dumps(clean_json(result),indent=2))
